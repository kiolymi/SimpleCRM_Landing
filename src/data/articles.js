export function getArticlesByCategory(category) {
  return articles.filter(article => article.category === category);
}

export function getArticleBySlug(slug) {
  return articles.find(article => article.slug === slug);
}

export function findArticles(query) {
  const normalize = value => String(value).normalize('NFKC').toLocaleLowerCase('ru').replaceAll('ё', 'е');
  const queryText = normalize(query)
    .replace(/не оплатил[аи]?|оплата|оплату|оплате/g, 'оплат')
    .replace(/клиент не отвечает/g, 'контакт')
    .replace(/напомнить|напоминания|напоминание/g, 'напомин')
    .replace(/повторная запись|повторную запись/g, 'повторн')
    .replace(/перенести встречу|перенос встречи/g, 'перенос');
  const terms = queryText.match(/[\p{L}\p{N}]+/gu) || [];
  if (!terms.length) return [];
  return articles.filter(article => {
    const text = normalize([
      article.title,
      article.excerpt,
      ...(article.tags || []),
      ...(article.content || []).map(block => block.text || ''),
    ].join(' '));
    return terms.every(term => text.includes(term));
  });
}
